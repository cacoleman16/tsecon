#!/usr/bin/env python3
"""Render benchmarks/results/latest.json into the public speed dashboard.

    python benchmarks/render_dashboard.py                # writes docs/reference/speed.md
    python benchmarks/render_dashboard.py --check        # exit 1 if the page is stale

The page follows the harness's accuracy-before-speed rule: the parity matrix
is rendered FIRST and is the deliverable; the timing table comes after it,
under the machine/build caveats; a reproduce block closes the page. Nothing
on the page is typed by hand -- every number is read from the JSON that
`benchmarks/bench.py --json` wrote.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_JSON = os.path.join(HERE, "results", "latest.json")
DEFAULT_OUT = os.path.join(REPO, "docs", "reference", "speed.md")
README = os.path.join(REPO, "README.md")
README_BULLET_PREFIX = "- **[Benchmarks](benchmarks/)** —"
BENCH_README = "https://github.com/cacoleman16/tsecon/blob/main/benchmarks/README.md"
RESULTS_URL = "https://github.com/cacoleman16/tsecon/blob/main/benchmarks/results/latest.json"


def _cell(text: str) -> str:
    """Escape a string for a Markdown table cell."""
    return str(text).replace("|", "\\|")


def _fmt_tol(tol: float) -> str:
    return "exact (0)" if tol == 0 else f"{tol:.0e}"


def render(doc: dict) -> str:
    m, v, b = doc["machine"], doc["versions"], doc["build"]
    cases = doc["cases"]
    n_metrics = sum(len(c["parity"]) for c in cases)
    n_pass = sum(p["passed"] for c in cases for p in c["parity"])
    all_pass = doc["all_parity_passed"]
    timed = [c for c in cases if c["timing"] is not None]
    faster = [c for c in timed if c["timing"]["ratio_ref_over_tsecon"] > 1]
    slower = [c for c in timed if c["timing"]["ratio_ref_over_tsecon"] <= 1]
    build_mode = b["mode"].upper()
    date = doc["generated_at"][:10]

    out: list[str] = []
    w = out.append
    w("<!-- GENERATED by benchmarks/render_dashboard.py from benchmarks/results/latest.json.")
    w("     Do not edit by hand: re-run `python benchmarks/bench.py --json benchmarks/results/latest.json`")
    w("     and then `python benchmarks/render_dashboard.py`. -->")
    w("")
    w("# Speed dashboard")
    w("")
    w("**Accuracy before speed.** This page is generated from one run of the")
    w(f"[benchmark harness]({BENCH_README}), whose rule is that an estimate must")
    w("match an independent reference (statsmodels, `arch`, SciPy, scikit-learn) at a")
    w("stated tolerance *before* it is timed. The parity matrix therefore comes")
    w("first and is the deliverable; the timings below it are indicative,")
    w("single-machine numbers and are labelled with the build that produced them.")
    w("")
    verdict = "ALL PASS" if all_pass else "FAILURE(S) PRESENT"
    w(f"| | |")
    w(f"|---|---|")
    w(f"| **Parity** | **{n_pass}/{n_metrics} metrics across {len(cases)} operations: {verdict}** |")
    w(f"| Faster than the reference | {len(faster)}/{len(timed)} timed operations ({build_mode} build) |")
    w(f"| Slower than the reference | {len(slower)}/{len(timed)} — published below, not dropped |")
    w(f"| Measured | {date}, tsecon {v['tsecon']}, {m['cpu_model']} ({m['cpu_count']} cores) |")
    w("")
    w("---")
    w("")
    w("## 1. Parity matrix — the deliverable")
    w("")
    w("`max abs diff` is the largest absolute disagreement between tsecon and the")
    w("reference on that metric; `tol` is the tolerance the harness asserts, set")
    w("from the *known* source of numerical difference (machine precision for")
    w("closed-form linear algebra, optimiser tolerance for iterative QMLE fits) and")
    w("never widened to pass. This table is machine-independent: a debug build")
    w("produces the identical matrix.")
    w("")
    w("| Operation | Metric | max abs diff | tol | Result |")
    w("|---|---|---:|---:|:---:|")
    for c in cases:
        first = True
        for p in c["parity"]:
            op = f"**{_cell(c['op'])}**<br>vs `{_cell(c['reference'])}`" if first else ""
            res = "PASS" if p["passed"] else "**FAIL**"
            w(f"| {op} | {_cell(p['metric'])} | {p['max_abs_diff']:.2e} | {_fmt_tol(p['tol'])} | {res} |")
            first = False
    w("")
    w(f"**Result: {n_pass}/{n_metrics} parity checks passed"
      + (" — the harness exited 0.**" if all_pass else " — the harness exited non-zero.**"))
    notes = [c for c in cases if c["note"]]
    if notes:
        w("")
        w("Tolerance notes recorded by the harness:")
        w("")
        for c in notes:
            w(f"- **{_cell(c['op'])}** — {c['note']}")
    if not doc["sklearn_available"]:
        w("")
        w("> **scikit-learn was not installed for this run**, so the ridge and elastic-net")
        w("> rows are absent and the matrix covers less than a full run.")
    w("")
    w("---")
    w("")
    w("## 2. Timings — indicative, subordinate to parity")
    w("")
    w("Read the caveats before the numbers:")
    w("")
    w(f"- **Build:** `{build_mode}` — detected via `{_cell(b['detail'])}`."
      + ("" if b["mode"] == "release" else
         " **This is not a release build; these timings are not speed claims.**"))
    w(f"- **Machine:** {m['cpu_model']}, {m['cpu_count']} cores, {m['platform']}"
      f" ({m['machine']}); Python {m['python']} ({m['python_implementation']}).")
    w(f"- **Versions:** tsecon {v['tsecon']}, numpy {v['numpy']}, scipy {v['scipy']},"
      f" statsmodels {v['statsmodels']}, arch {v['arch']},"
      f" scikit-learn {v['scikit-learn'] if v['scikit-learn'] else 'not installed'}.")
    w(f"- **Method:** best (minimum) of {doc['repeats']} wall-clock runs after a warm-up,"
      " on the harness's small synthetic inputs; the three QMLE volatility fits use"
      " at most 3 repeats. `ratio` is reference time / tsecon time, so values above 1"
      " mean tsecon was faster. Order-of-magnitude information only.")
    w(f"- **Date:** {doc['generated_at']}.")
    oh = doc.get("call_overhead")
    if oh:
        w(f"- **Per-call overhead:** the public `tsecon.kpss` took {oh['wrapped_s'] * 1e3:.3f} ms"
          f" against {oh['raw_core_s'] * 1e3:.3f} ms for the raw extension entry point"
          f" `tsecon._core.kpss` on the same array — a fixed ~{oh['overhead_s'] * 1e3:.3f} ms of"
          " Python-side argument validation per call. It is included in every tsecon"
          " timing below and dominates the rows whose compute is far below a millisecond;"
          " the ratios on those rows measure that wrapper, not the Rust core.")
    w("")
    w("| Operation | Reference | tsecon (ms) | reference (ms) | ratio | |")
    w("|---|---|---:|---:|---:|---|")
    for c in timed:
        t = c["timing"]
        r = t["ratio_ref_over_tsecon"]
        tag = "faster" if r > 1 else "**SLOWER**"
        w(f"| {_cell(c['op'])} | `{_cell(c['reference'])}` | {t['tsecon_s'] * 1e3:.3f}"
          f" | {t['reference_s'] * 1e3:.3f} | {r:.2f}x | {tag} |")
    w("")
    w(f"tsecon was faster on **{len(faster)} of {len(timed)}** timed operations in this run.")
    if slower:
        losses = ", ".join(
            f"{_cell(c['op'])} at {c['timing']['ratio_ref_over_tsecon']:.2f}x" for c in slower
        )
        w(f"The losses are published with the wins: {losses}. The harness README explains"
          " what was measured and deliberately *not* done about each of them.")
    w("")
    w("---")
    w("")
    w("## 3. How to reproduce")
    w("")
    w("Build a **release** extension first — `maturin develop` without `--release`")
    w("installs a debug build whose timings the harness refuses to label as speed")
    w("claims (the parity matrix is identical either way):")
    w("")
    w("```sh")
    w("pip install numpy scipy statsmodels arch scikit-learn maturin")
    w("cd bindings/python && maturin develop --release && cd ../..")
    w("python benchmarks/bench.py --json benchmarks/results/latest.json   # exits 0 iff every parity check passes")
    w("python benchmarks/render_dashboard.py                              # regenerates this page")
    w("python benchmarks/render_dashboard.py --check                      # exits 1 if the page is stale")
    w("```")
    w("")
    w(f"The committed [`benchmarks/results/latest.json`]({RESULTS_URL}) is the exact input")
    w("this page was rendered from; the harness's provenance banner (CPU, versions,")
    w("build mode) is stored in it, so any number quoted from this page can be traced")
    w("to the machine and build that produced it. Different hardware will move every")
    w("timing; it must not move a single parity row.")
    w("")
    return "\n".join(out)


def render_readme_bullet(doc: dict) -> str:
    """The README's one-paragraph benchmark summary, from the same JSON."""
    t = {c["op"]: c["timing"]["ratio_ref_over_tsecon"] for c in doc["cases"] if c["timing"]}
    n = len(t)
    faster = sum(1 for v in t.values() if v > 1)
    n_metrics = sum(len(c["parity"]) for c in doc["cases"])
    m = doc["machine"]

    def r(op):
        return t[op]

    adf = r("ADF test (regression='c', fixed lag=4)")
    var = r("VAR(2) coefficients (2 vars, trend='c')")
    jb = r("Jarque-Bera normality test")
    cf = r("Christiano-Fitzgerald band-pass (low=6, high=32)")
    gar = r("GARCH(1,1) QMLE (constant mean, normal)")
    eg = r("EGARCH(1,1,1) QMLE (constant mean, normal)")
    losses = sorted((op for op, v in t.items() if v <= 1), key=lambda op: t[op])
    sub_ms = [op for op in losses if "QMLE" not in op]
    sub_ms_txt = ""
    if sub_ms:
        short = [op.split(" (")[0].split(" test")[0] for op in sub_ms]
        names = short[0] if len(short) == 1 else ", ".join(short[:-1]) + " and " + short[-1]
        ratios = ", ".join(f"{t[op]:.2f}×" for op in sub_ms)
        oh = doc.get("call_overhead")
        why = (f"\n  where the Python wrapper's fixed ~{oh['overhead_s'] * 1e3:.2f} ms per-call cost dominates"
               if oh else "\n  where per-call overhead dominates")
        sub_ms_txt = f", and the\n  sub-millisecond {names} calls ({ratios}),{why}"
    parity = "All" if doc["all_parity_passed"] else "NOT all:"
    return (
        f"{README_BULLET_PREFIX} a parity-first harness: estimates must match a\n"
        f"  reference *before* anything is timed. {parity} {n_metrics} parity metrics across {n}\n"
        f"  operations pass. On a release build in the Linux CI-style container\n"
        f"  ({m['cpu_model']}, {m['cpu_count']} cores) tsecon is faster on {faster} of {n} operations —\n"
        f"  ADF {adf:.1f}×, VAR(2) {var:.1f}×, Jarque-Bera {jb:.1f}× and the Christiano-Fitzgerald\n"
        f"  filter {cf:.1f}× the speed of statsmodels — and slower on {n - faster}, which we publish\n"
        f"  too: GARCH(1,1) QMLE at {gar:.2f}× the speed of `arch` (about {1 / gar:.0f}× *slower*), EGARCH at\n"
        f"  {eg:.2f}×{sub_ms_txt}.\n"
        f"  The parity matrix and every timing live on the\n"
        f"  [speed dashboard](docs/reference/speed.md), rendered from the\n"
        f"  committed [`benchmarks/results/latest.json`](benchmarks/results/latest.json).\n"
    )


def update_readme(doc: dict, path: str = README) -> bool:
    """Replace the README's benchmark bullet (found by its fixed prefix, through
    the end of that list item) with the rendered one. Returns True if changed."""
    with open(path) as fh:
        lines = fh.read().split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.startswith(README_BULLET_PREFIX)]
    if len(starts) != 1:
        raise SystemExit(f"expected exactly one README line starting with {README_BULLET_PREFIX!r}, found {len(starts)}")
    i = starts[0]
    j = i + 1
    while j < len(lines) and lines[j].startswith("  ") and lines[j].strip():
        j += 1
    new_lines = render_readme_bullet(doc).rstrip("\n").split("\n")
    if lines[i:j] == new_lines:
        return False
    lines[i:j] = new_lines
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description="render the speed dashboard from bench.py --json output")
    ap.add_argument("--json", default=DEFAULT_JSON, help=f"input (default {os.path.relpath(DEFAULT_JSON, REPO)})")
    ap.add_argument("--out", default=DEFAULT_OUT, help=f"output (default {os.path.relpath(DEFAULT_OUT, REPO)})")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if --out differs from the render")
    ap.add_argument("--readme", action="store_true",
                    help="also rewrite the benchmark bullet in README.md from the same JSON")
    args = ap.parse_args()
    with open(args.json) as fh:
        doc = json.load(fh)
    text = render(doc)
    if args.readme and not args.check:
        changed = update_readme(doc)
        print(f"{'updated' if changed else 'unchanged'} benchmark bullet in {README}")
    if args.check:
        try:
            with open(args.out) as fh:
                current = fh.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f"STALE: {args.out} does not match a fresh render of {args.json}")
            return 1
        print(f"OK: {args.out} is up to date with {args.json}")
        return 0
    with open(args.out, "w") as fh:
        fh.write(text)
    print(f"wrote {args.out} from {args.json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
