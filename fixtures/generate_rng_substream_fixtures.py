"""Golden values for lazily derived RNG substreams (fixtures/rng_substreams.json).

The library's parallel Monte Carlo contract keys replication ``i`` of a seed
to child ``i`` of ``numpy.random.SeedSequence(seed).spawn(n)``. NumPy defines
that child as ``SeedSequence(entropy=seed, spawn_key=(i,))`` — it depends on
``(seed, i)`` only — so a replication loop can derive its stream inside the
task instead of materializing ``n`` streams first (the vector that a draw count
of 2**31 used to size, aborting the process on a 154 GB allocation).

This generator pins, for several seeds and child indices up to the last one
the 32-bit spawn-key space admits (``2**32 - 1``), the NumPy reference of:

* ``state_uint32_4`` — ``SeedSequence(seed, spawn_key=(i,)).generate_state(4,
  np.uint32)``, the child's pool squeezed into state words;
* ``raw_uint64`` — the first 6 ``Philox(seed=child).random_raw()`` outputs;
* ``uniform_f64`` — the first 3 ``Generator(Philox(seed=child)).random()``
  draws.

It also asserts, for the small indices, that the directly constructed child is
the one ``SeedSequence(seed).spawn(n)`` hands out (the identity the lazy
derivation rests on), and records the first two raws of every child of
``spawn(1100)`` for one seed so a replication driver can be checked across a
1024-child chunk boundary.

Run:  python fixtures/generate_rng_substream_fixtures.py
Never imports tsecon. Derived numbers only; integers are decimal strings
(JSON numbers cannot hold a u64).
"""
import json
import platform
from pathlib import Path

import numpy as np

OUT = Path(__file__).parent / "rng_substreams.json"
META = {"numpy": np.__version__, "python": platform.python_version()}

SEEDS = [0, 1, 20260716, 2**32 + 5, 2**64 - 1]
INDICES = [0, 1, 2, 1023, 1024, 65535, 65536, 2**31 - 1, 2**31, 2**32 - 1]
SPAWN_CHECK_N = 8  # spawn(n) identity checked for every index below this
DRIVER_SEED = 20260716
DRIVER_N = 1100


def child(seed: int, index: int) -> np.random.SeedSequence:
    return np.random.SeedSequence(entropy=seed, spawn_key=(index,))


def case(seed: int, index: int) -> dict:
    c = child(seed, index)
    raw = np.random.Philox(seed=c).random_raw(6)
    uni = np.random.Generator(np.random.Philox(seed=child(seed, index))).random(3)
    return {
        "seed": str(seed),
        "index": index,
        "state_uint32_4": [str(int(x)) for x in c.generate_state(4, np.uint32)],
        "raw_uint64": [str(int(x)) for x in raw],
        "uniform_f64": [float(x) for x in uni],
    }


def main() -> None:
    for seed in SEEDS:
        spawned = np.random.SeedSequence(seed).spawn(SPAWN_CHECK_N)
        for i, s in enumerate(spawned):
            assert tuple(s.spawn_key) == (i,)
            d = child(seed, i)
            assert np.array_equal(s.generate_state(4, np.uint32), d.generate_state(4, np.uint32))
            assert np.array_equal(
                np.random.Philox(seed=s).random_raw(4), np.random.Philox(seed=d).random_raw(4)
            )

    cases = [case(seed, i) for seed in SEEDS for i in INDICES]

    driver = [
        [str(int(x)) for x in np.random.Philox(seed=c).random_raw(2)]
        for c in np.random.SeedSequence(DRIVER_SEED).spawn(DRIVER_N)
    ]

    obj = {
        "_meta": META,
        "_doc": (
            "Lazily derived substreams: child i of SeedSequence(seed).spawn(n) is "
            "SeedSequence(entropy=seed, spawn_key=(i,)); per (seed, index) its "
            "generate_state(4, uint32), the first 6 Philox(seed=child).random_raw() and "
            "the first 3 Generator(Philox(seed=child)).random(). 'driver' is the first "
            "two raws of every child of SeedSequence(20260716).spawn(1100). Generated by "
            "fixtures/generate_rng_substream_fixtures.py; never imports tsecon."
        ),
        "cases": cases,
        "driver": {"seed": str(DRIVER_SEED), "n": DRIVER_N, "raw_uint64_2": driver},
    }
    OUT.write_text(json.dumps(obj, indent=1) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(cases)} cases)")


if __name__ == "__main__":
    main()
