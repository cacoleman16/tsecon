"""Writes crates/tsecon-coint/src/pss.rs: the Pesaran-Shin-Smith (2001)
bounds-test response surface transcribed verbatim from statsmodels
``statsmodels/tsa/ardl/pss_critical_values.py`` (BSD-3-Clause).

Run with the reference venv (statsmodels 0.15.0); the output is committed.
Every constant is printed with ``repr`` so the Rust literal parses to the
same double; ``fixtures/ardl.json`` (block ``pss_table``) re-exports the
same constants and ``ardl_golden.rs`` asserts them bit for bit.
"""
from pathlib import Path

import statsmodels
from statsmodels.tsa.ardl import pss_critical_values as pss

OUT = Path(__file__).parents[2] / "crates" / "tsecon-coint" / "src" / "pss.rs"


def lit(v):
    s = repr(float(v))
    return s if ("." in s or "e" in s) else s + ".0"


def arr(vals):
    return "[" + ", ".join(lit(v) for v in vals) + "]"


keys = sorted(pss.crit_vals)
assert len(keys) == 100
lines = []
lines.append(f"""//! The Pesaran-Shin-Smith (2001) bounds-test **response surface**: the
//! asymptotic critical values of the PSS F statistic and the polynomial
//! p-value surface, for `k = 1 ..= 10` regressors, the five PSS cases and
//! the two bounds (all regressors I(0) — the lower bound — or all I(1) —
//! the upper bound).
//!
//! Transcribed verbatim (every constant, generated by
//! `lab/ardl/transcribe_pss.py`) from statsmodels {statsmodels.__version__}
//! `statsmodels/tsa/ardl/pss_critical_values.py` — Copyright (C) 2006
//! Jonathan E. Taylor, (c) 2006-2008 Scipy Developers, (c) 2009-2018
//! statsmodels Developers; BSD-3-Clause (see THIRD-PARTY-LICENSES.md).
//! statsmodels computed the surface from 32 000 000 simulations per key
//! (PSS used 40 000) in the PSS design
//! (`statsmodels/tsa/ardl/_pss_critical_values/pss.py`, in which `k` is
//! the number of REGRESSORS). The p-value is
//!
//! ```text
//! p = 1 - Phi(a_0 + a_1 x + a_2 x^2 [+ a_3 x^3]),   x = ln F,
//! ```
//!
//! with the cubic `LARGE_P` coefficients for `F <= stat_star` and the
//! quadratic `SMALL_P` ones for `F > stat_star` (strictly), evaluated here
//! with the normal survival function for relative accuracy in the tail.
//! The surface jumps at `stat_star` (by up to 0.0165) and is non-monotone
//! for eight keys at `F < 0.17` (where `p > 0.9996`); neither is smoothed.
//!
//! The table key is `k = n_x`, the number of regressors — NOT the
//! `1 + n_x` statsmodels' `bounds_test` passes (see the model card).

use tsecon_stats::{{ContinuousDist, StdNormal}};

/// One key of the surface: `(k, case, i1)`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PssEntry {{
    /// Number of regressors `k` (1 ..= 10).
    pub k: u8,
    /// PSS case (1 ..= 5).
    pub case: u8,
    /// `true` for the I(1) (upper) bound, `false` for the I(0) (lower).
    pub i1: bool,
    /// Critical values at the 90%, 95%, 99% and 99.9% levels.
    pub crit: [f64; 4],
    /// Cubic p-value polynomial in `ln F`, used for `F <= stat_star`.
    pub large_p: [f64; 4],
    /// Quadratic p-value polynomial in `ln F`, used for `F > stat_star`.
    pub small_p: [f64; 3],
    /// The switch point between the two polynomials.
    pub stat_star: f64,
}}

/// The levels the critical values are tabulated at.
pub const CRIT_LEVELS: [f64; 4] = [0.90, 0.95, 0.99, 0.999];

/// Largest regressor count the surface covers.
pub const MAX_K: usize = 10;

/// Every key, sorted by `(k, case, i1)` (`i1 = false` first).
pub const PSS_TABLE: [PssEntry; 100] = [""")
for key in keys:
    k, case, i1 = key
    # the layout rustfmt gives the literal, so `cargo fmt` is a no-op on it
    lines.append("    PssEntry {")
    lines.append(f"        k: {k},")
    lines.append(f"        case: {case},")
    lines.append(f"        i1: {'true' if i1 else 'false'},")
    lines.append(f"        crit: {arr(pss.crit_vals[key])},")
    lines.append(f"        large_p: {arr(pss.large_p[key])},")
    lines.append(f"        small_p: {arr(pss.small_p[key])},")
    lines.append(f"        stat_star: {lit(pss.stat_star[key])},")
    lines.append("    },")
lines.append("""];

/// The entry at `(k, case, i1)`, or `None` outside `k = 1 ..= 10`,
/// `case = 1 ..= 5`.
pub fn entry(k: usize, case: usize, i1: bool) -> Option<&'static PssEntry> {
    if !(1..=MAX_K).contains(&k) || !(1..=5).contains(&case) {
        return None;
    }
    let idx = (k - 1) * 10 + (case - 1) * 2 + usize::from(i1);
    PSS_TABLE.get(idx)
}

/// Critical values at [`CRIT_LEVELS`] for `(k, case, i1)`.
pub fn crit_values(k: usize, case: usize, i1: bool) -> Option<[f64; 4]> {
    entry(k, case, i1).map(|e| e.crit)
}

/// Response-surface p-value of the PSS F statistic `stat` at
/// `(k, case, i1)`: `StdNormal.sf(sum_i a_i (ln stat)^i)`, `a` the
/// quadratic `small_p` when `stat > stat_star` (strictly) and the cubic
/// `large_p` otherwise. `stat <= 0` (an exactly-zero level block) is
/// `p = 1`; a NaN statistic is NaN.
pub fn pvalue(stat: f64, k: usize, case: usize, i1: bool) -> Option<f64> {
    let e = entry(k, case, i1)?;
    if stat.is_nan() {
        return Some(f64::NAN);
    }
    if stat <= 0.0 {
        return Some(1.0);
    }
    let x = stat.ln();
    let z = if stat > e.stat_star {
        e.small_p[0] + x * (e.small_p[1] + x * e.small_p[2])
    } else {
        e.large_p[0] + x * (e.large_p[1] + x * (e.large_p[2] + x * e.large_p[3]))
    };
    Some(StdNormal.sf(z))
}
""")
OUT.write_text("\n".join(lines))
