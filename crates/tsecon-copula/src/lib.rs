/// Empirical Kendall tau-b of two equal-length series (scipy
/// `kendalltau` semantics, ties included) — exposed because the
/// tau-inversion route makes it a quantity users will want directly.
///
/// # Errors
///
/// [`CopulaError::EmptyInput`] / [`CopulaError::NonFinite`] /
/// [`CopulaError::LengthMismatch`] on malformed input;
/// [`CopulaError::Degenerate`] when a column is constant.
pub fn kendall_tau(x: &[f64], y: &[f64]) -> Result<f64, CopulaError> {
    common::check_series(x, "x")?;
    common::check_series(y, "y")?;
    if x.len() != y.len() {
        return Err(CopulaError::LengthMismatch {
            n1: x.len(),
            n2: y.len(),
        });
    }
    common::kendall_tau(x, y)
}
